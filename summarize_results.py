#!/usr/bin/env python3
"""Collate results/*.json into RESULTS.md (a human-readable table of every
metric reported by the pipeline). Re-run any time; safe if some JSONs are
missing."""
import os, json, datetime
import numpy as np

ROOT = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(ROOT, "results")


def L(name):
    p = os.path.join(RES, name)
    try:
        return json.load(open(p)) if os.path.exists(p) else None
    except Exception:
        return None


def row(cells):
    return "| " + " | ".join(cells) + " |"


def fnum(x, d=2):
    try:
        return f"{x:.{d}f}"
    except Exception:
        return "–"


out = []
out.append("# Results\n")
out.append(f"_Auto-generated by `summarize_results.py` on "
           f"{datetime.datetime.now():%Y-%m-%d %H:%M}._\n")
out.append("Feature-count K, feature ranking, clustering and all model "
           "hyper-parameters are selected on **training data only** "
           "(nested LOO for Pakistan; 5-fold CV on the train split for Germany). "
           "NNLS reconstruction now supports L2-regularised weights and a wider "
           "neighbour range.\n")

# ── Pakistan & Germany deep models ──
for site, loader, keyfn in [
    ("Pakistan (Balakot) — nested LOO",
     lambda f: L(f"pakistan_{f}.json"),
     lambda r: r["test"]),
    ("Germany (Karlsruhe) — 85/15 hold-out",
     lambda f: L(f"german_{f}.json"),
     lambda r: r["combined_test"])]:
    out.append(f"\n## {site}\n")
    out.append(row(["Backbone", "Model", "%RMSE", "R²", "RMSE", "MAE", "K"]))
    out.append(row(["---"] * 7))
    for feat in ["dino", "resnet50"]:
        d = loader(feat)
        if not d:
            continue
        for m, r in d["methods"].items():
            mt = keyfn(r)
            if not mt:
                continue
            k = r.get("K_modal", "")
            out.append(row([feat, m.upper(), fnum(mt["percent_rmse"]),
                            fnum(mt["r2"], 3), fnum(mt["rmse"]),
                            fnum(mt["mae"]), str(k)]))
    # literature
    lit = L("literature_baselines.json")
    if lit:
        key = "pakistan" if site.startswith("Pakistan") else "german"
        for name, mt in lit.get(key, {}).items():
            out.append(row(["literature/GLCM", name.upper(), fnum(mt["percent_rmse"]),
                            fnum(mt["r2"], 3), fnum(mt["rmse"]), fnum(mt["mae"]), "–"]))

# ── German ablations ──
out.append("\n## Germany ablations (DINO & ResNet50)\n")
out.append(row(["Backbone", "Ablation", "Model", "%RMSE", "R²"]))
out.append(row(["---"] * 5))
for feat in ["dino", "resnet50"]:
    a = L(f"ablations_german_{feat}.json")
    if not a:
        continue
    for m, mt in a.get("all_features", {}).items():
        if mt:
            out.append(row([feat, "all-features", m.upper(),
                            fnum(mt["percent_rmse"]), fnum(mt["r2"], 3)]))
    for m, v in a.get("no_clustering", {}).items():
        mt = v["test"]
        out.append(row([feat, "no-clustering", m.upper(),
                        fnum(mt["percent_rmse"]), fnum(mt["r2"], 3)]))

# ── Robustness ──
rob = L("robustness_german.json")
if rob and "summary" in rob:
    out.append(f"\n## Germany robustness — {rob.get('seeds','?')} stratified 85/15 splits "
               f"(mean ± std)\n")
    out.append(row(["Backbone", "Config", "Model", "%RMSE mean±std", "R² mean±std", "n"]))
    out.append(row(["---"] * 6))
    for k in sorted(rob["summary"]):
        s = rob["summary"][k]
        feat, cfg, m = k.split("|")
        out.append(row([feat, cfg, m.upper(),
                        f"{fnum(s['prmse_mean'])} ± {fnum(s['prmse_std'])}",
                        f"{fnum(s['r2_mean'],2)} ± {fnum(s['r2_std'],2)}",
                        str(s["n_seeds"])]))

txt = "\n".join(out) + "\n"
open(os.path.join(ROOT, "RESULTS.md"), "w").write(txt)
print("wrote RESULTS.md")
print(txt)
